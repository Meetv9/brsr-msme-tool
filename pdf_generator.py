def render_section_a(pdf, d):
    """Renders full Section A exactly as before."""
    pdf.section_heading("SECTION A - GENERAL DISCLOSURES")

    # ── I. Company Identity ──────────────────────────────────────────────
    pdf.sub_heading("I. Company Identity")
    pdf.kv_row("Company Name", d.get("company_name"), shaded=True)
    pdf.kv_row("CIN Number", d.get("cin") or "N/A (Proprietorship/Partnership)")
    pdf.kv_row("Year of Incorporation", d.get("year_started"), shaded=True)
    pdf.kv_row("Business Type", d.get("ownership"))
    pdf.kv_row("Financial Year", d.get("financial_year"), shaded=True)
    rb = d.get("reporting_boundary", "-")
    if isinstance(rb, str):
        rb = rb.split("-")[0].strip()
    pdf.kv_row("Reporting Boundary", rb)
    if str(d.get("listed", "")).startswith("Yes"):
        pdf.kv_row("Listed on Exchange",
                   ", ".join(d.get("stock_exchange", [])) or "-", shaded=True)
        pdf.kv_row("Paid-up Capital", d.get("paid_up_capital", "-"))

    # ── II. Contact Details ──────────────────────────────────────────────
    pdf.sub_heading("II. Contact Details")
    pdf.kv_row("Registered Office", d.get("address"), shaded=True)
    pdf.kv_row("Corporate Office", d.get("corporate_address") or d.get("address"))
    pdf.kv_row("Email", d.get("email"), shaded=True)
    pdf.kv_row("Phone", d.get("phone"))
    pdf.kv_row("Website", d.get("website") or "Not available", shaded=True)

    # ── III. BRSR Contact Person ────────────────────────────────────────
    pdf.sub_heading("III. BRSR Contact Person")
    pdf.kv_row("Name", d.get("brsr_person_name"), shaded=True)
    pdf.kv_row("Designation", d.get("brsr_person_designation"))
    pdf.kv_row("Email", d.get("brsr_person_email"), shaded=True)
    pdf.kv_row("Phone", d.get("brsr_person_phone"))

    # ── IV. Products/Services ───────────────────────────────────────────
    pdf.sub_heading("IV. Business Activities & Products")
    activities = d.get("activities", [])
    if activities:
        cols = ["S.No.", "Main Activity", "Business Activity", "% of Turnover"]
        widths = [15, 55, 75, 40]
        pdf.table_header(cols, widths)
        for i, act in enumerate(activities, 1):
            pdf.table_row(
                [str(i), act.get("main", "-"), act.get("sub", "-"),
                 f"{act.get('pct', 0)}%"],
                widths, shaded=(i % 2 == 0)
            )

    products = d.get("products", [])
    if products:
        pdf.ln(2)
        pdf.info_label("Products/Services (covering 90% of turnover)")
        cols = ["S.No.", "Product/Service", "NIC Code", "% of Turnover"]
        widths = [15, 90, 40, 40]
        pdf.table_header(cols, widths)
        for i, prod in enumerate(products, 1):
            pdf.table_row(
                [str(i), prod.get("name", "-"), prod.get("nic", "-"),
                 f"{prod.get('pct', 0)}%"],
                widths, shaded=(i % 2 == 0)
            )

    # ── V. Operations ──────────────────────────────────────────────────
    pdf.add_page()
    pdf.sub_heading("V. Operations")
    pdf.kv_row("Number of Plants / Offices in India",
               d.get("num_plants", 0), shaded=True)
    pdf.kv_row("States of Operation", d.get("num_states", "-"))
    pdf.kv_row("Number of Countries (Export)",
               d.get("num_countries", 0), shaded=True)

    # ── VI. Markets ───────────────────────────────────────────────────
    pdf.sub_heading("VI. Markets Served")
    pdf.kv_row("States in India", d.get("num_states", "-"), shaded=True)
    pdf.kv_row("Countries Exported To", d.get("num_countries", 0))
    pdf.kv_row("Export as % of Revenue", f"{d.get('export_pct', 0)}%", shaded=True)
    cust = d.get("customer_types", [])
    pdf.kv_row("Customer Types", ", ".join(cust) if cust else "-")

    # ── VII. Employees & Workers ─────────────────────────────────────────
    pdf.add_page()
    pdf.sub_heading("VII. Employees & Workers")
    cols = ["Category", "Total", "Male", "Female", "% Female"]
    widths = [62, 28, 28, 28, 39]
    pdf.table_header(cols, widths)

    def female_pct(f, t):
        return f"{pct(f, t)}%" if t else "0%"

    rows = [
        ("Permanent Employees",
         d.get("total_perm_emp", 0), d.get("perm_emp_male", 0),
         d.get("perm_emp_female", 0),
         female_pct(d.get("perm_emp_female", 0), d.get("total_perm_emp", 1))),
        ("Contract Employees",
         d.get("total_temp_emp", 0), d.get("temp_emp_male", 0),
         d.get("temp_emp_female", 0),
         female_pct(d.get("temp_emp_female", 0), d.get("total_temp_emp", 1))),
        ("Permanent Workers",
         d.get("total_perm_wkr", 0), d.get("perm_wkr_male", 0),
         d.get("perm_wkr_female", 0),
         female_pct(d.get("perm_wkr_female", 0), d.get("total_perm_wkr", 1))),
        ("Contract Workers",
         d.get("total_temp_wkr", 0), d.get("temp_wkr_male", 0),
         d.get("temp_wkr_female", 0),
         female_pct(d.get("temp_wkr_female", 0), d.get("total_temp_wkr", 1))),
        ("Differently Abled Employees",
         d.get("diff_emp", 0), "-", "-", "-"),
        ("Differently Abled Workers",
         d.get("diff_wkr", 0), "-", "-", "-"),
    ]
    for i, row in enumerate(rows):
        pdf.table_row(list(row), widths, shaded=(i % 2 == 0))
    pdf.ln(2)

    # ── VIII. Women in Leadership ────────────────────────────────────────
    if d.get("board_total", 0) > 0 or d.get("kmp_total", 0) > 0:
        pdf.sub_heading("VIII. Women in Leadership")
        cols = ["Role", "Total", "Women", "% Women"]
        widths = [80, 37, 37, 31]
        pdf.table_header(cols, widths)
        pdf.table_row(["Board of Directors",
                       str(d.get("board_total", 0)),
                       str(d.get("board_female", 0)),
                       female_pct(d.get("board_female", 0),
                                  d.get("board_total", 1))],
                      widths, shaded=True)
        pdf.table_row(["Key Management Personnel (KMP)",
                       str(d.get("kmp_total", 0)),
                       str(d.get("kmp_female", 0)),
                       female_pct(d.get("kmp_female", 0),
                                  d.get("kmp_total", 1))], widths)
        pdf.ln(2)
        if d.get("board_female", 0) == 0 and d.get("board_total", 0) > 0:
            pdf.recommendation(
                "No women on the Board of Directors. Adding at least one woman "
                "director improves ESG credibility and is increasingly expected "
                "by banks, large buyers, and government schemes."
            )

    # ── IX. Staff Turnover ───────────────────────────────────────────────
    pdf.sub_heading("IX. Staff Turnover Rate (3-Year Trend)")
    cols = ["Category", "FY 2024-25", "FY 2023-24", "FY 2022-23"]
    widths = [80, 37, 37, 31]
    pdf.table_header(cols, widths)
    pdf.table_row(["Permanent Employees",
                   f"{d.get('turnover_fy1', 0)}%",
                   f"{d.get('turnover_fy2', 0)}%",
                   f"{d.get('turnover_fy3', 0)}%"], widths, shaded=True)
    pdf.ln(2)

    # ── X. CSR ───────────────────────────────────────────────────────────
    pdf.sub_heading("X. CSR (Section 135, Companies Act 2013)")
    csr = str(d.get("csr_applicable", "Not Applicable"))
    if "Not Applicable" in csr:
        pdf.kv_row("CSR Applicability", "Not Applicable - below threshold")
    else:
        pdf.kv_row("CSR Applicability", "Applicable", shaded=True)
        pdf.kv_row("Annual Turnover", d.get("csr_turnover", "-"))
