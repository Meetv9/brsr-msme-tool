class BRSRReport(FPDF):

    def header(self):
        # Skip header on cover page (page 1)
        if self.page_no() == 1:
            return

        # Indigo bar (matches SaaS theme)
        self.set_fill_color(99, 102, 241)
        self.rect(0, 0, 210, 14, 'F')
        self.set_text_color(255, 255, 255)
        self.set_font("Helvetica", "B", 10)
        self.set_y(4)
        self.cell(0, 6, "BUSINESS RESPONSIBILITY & SUSTAINABILITY REPORT", align="C")
        self.set_text_color(0, 0, 0)
        self.ln(12)

    def footer(self):
        # Skip footer on cover page
        if self.page_no() == 1:
            return
        self.set_y(-15)
        self.set_font("Helvetica", "I", 7.5)
        self.set_text_color(148, 163, 184)
        self.cell(0, 4,
                  f"Generated by Ecosetu  |  Green compliance, bridged.  |  "
                  f"{datetime.now().strftime('%d %B %Y')}  |  Page {self.page_no()}",
                  align="C")
    # ── SECTION HEADING (full bar) ──────────────────────────────────────
    def section_heading(self, text):
        self.ln(4)
        self.set_fill_color(21, 128, 61)
        self.set_text_color(255, 255, 255)
        self.set_font("Helvetica", "B", 10)
        self.cell(0, 8, f"  {clean(text)}", fill=True, ln=True)
        self.set_text_color(0, 0, 0)
        self.ln(2)

    # ── PRINCIPLE HEADING (smaller bar with icon) ───────────────────────
    def principle_heading(self, code, title):
        self.ln(3)
        self.set_fill_color(46, 125, 50)
        self.set_text_color(255, 255, 255)
        self.set_font("Helvetica", "B", 11)
        self.cell(0, 9, f"  {clean(code)}: {clean(title)}", fill=True, ln=True)
        self.set_text_color(0, 0, 0)
        self.ln(2)

    # ── SUB HEADING ─────────────────────────────────────────────────────
    def sub_heading(self, text):
        self.ln(2)
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(21, 128, 61)
        self.cell(0, 6, clean(text), ln=True)
        self.set_text_color(0, 0, 0)

    # ── KEY-VALUE ROW ───────────────────────────────────────────────────
    def kv_row(self, label, value, shaded=False):
        if shaded:
            self.set_fill_color(245, 250, 245)
        else:
            self.set_fill_color(255, 255, 255)
        self.set_font("Helvetica", "", 9)
        self.set_text_color(90, 90, 90)
        self.cell(70, 7, f"  {clean(label)}", border="B", fill=True)
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(0, 0, 0)
        v = clean(value) if value not in [None, "", 0, "0"] else "-"
        self.cell(0, 7, f"  {v}", border="B", fill=True, ln=True)

    # ── TABLE HEADER ────────────────────────────────────────────────────
    def table_header(self, cols, widths):
        self.set_fill_color(220, 240, 220)
        self.set_font("Helvetica", "B", 8)
        self.set_text_color(21, 80, 40)
        for col, w in zip(cols, widths):
            self.cell(w, 7, f" {clean(col)}", border=1, fill=True)
        self.ln()
        self.set_text_color(0, 0, 0)

    # ── TABLE ROW ───────────────────────────────────────────────────────
    def table_row(self, values, widths, shaded=False):
        if shaded:
            self.set_fill_color(250, 252, 250)
        else:
            self.set_fill_color(255, 255, 255)
        self.set_font("Helvetica", "", 8)
        for val, w in zip(values, widths):
            v = clean(val) if val not in [None, ""] else "-"
            self.cell(w, 6, f" {v}", border=1, fill=True)
        self.ln()

    # ── MULTI-LINE PARAGRAPH ────────────────────────────────────────────
    def paragraph(self, text, italic=False):
        self.set_font("Helvetica", "I" if italic else "", 9)
        self.set_text_color(70, 70, 70)
        self.multi_cell(0, 5, clean(text))
        self.set_text_color(0, 0, 0)
        self.ln(1)

    # ── ESG SCORE BOX ───────────────────────────────────────────────────
    def esg_score_box(self, score, label="ESG Readiness Score"):
        self.ln(4)
        self.set_fill_color(240, 250, 240)
        self.set_draw_color(21, 128, 61)
        self.set_line_width(0.5)
        self.rect(14, self.get_y(), 182, 28, 'FD')

        y = self.get_y() + 4
        self.set_xy(20, y)
        self.set_font("Helvetica", "B", 11)
        self.set_text_color(21, 80, 40)
        self.cell(80, 6, clean(label))

        self.set_font("Helvetica", "B", 22)
        if score >= 70:
            self.set_text_color(21, 128, 61)
        elif score >= 40:
            self.set_text_color(200, 130, 0)
        else:
            self.set_text_color(180, 30, 30)
        self.cell(30, 10, f"{score}%")

        self.set_font("Helvetica", "B", 10)
        if score >= 70:
            rating = "HIGH - Strong ESG posture"
            self.set_text_color(21, 128, 61)
        elif score >= 40:
            rating = "MEDIUM - Room to improve"
            self.set_text_color(200, 130, 0)
        else:
            rating = "LOW - Action needed"
            self.set_text_color(180, 30, 30)
        self.cell(60, 10, rating)

        self.set_text_color(0, 0, 0)
        self.ln(18)

    # ── RECOMMENDATION BOX ──────────────────────────────────────────────
    def recommendation(self, text):
        self.set_fill_color(255, 251, 230)
        self.set_draw_color(200, 150, 0)
        self.set_line_width(0.3)
        self.set_font("Helvetica", "", 8)
        self.set_text_color(100, 70, 0)
        self.multi_cell(0, 5, f"  Recommendation:  {clean(text)}", border=1, fill=True)
        self.set_text_color(0, 0, 0)
        self.set_draw_color(0, 0, 0)
        self.ln(1)

    # ── SMALL INFO LABEL ────────────────────────────────────────────────
    def info_label(self, text):
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(100, 100, 100)
        self.cell(0, 5, f"  {clean(text)}", ln=True)
        self.set_text_color(0, 0, 0)
        self.ln(1)


