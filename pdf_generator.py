def get_msme_class(turnover_lakhs):
    if turnover_lakhs == 0:
        return "-"
    if turnover_lakhs <= 500:
        return "Micro Enterprise"
    elif turnover_lakhs <= 5000:
        return "Small Enterprise"
    else:
        return "Medium Enterprise"


def safe_get(d, *keys, default="-"):
    """Safely traverse nested dicts. safe_get(data, 'p1', 'score', default=0)"""
    cur = d
    for k in keys:
        if isinstance(cur, dict):
            cur = cur.get(k)
        else:
            return default
    if cur is None or cur == "":
        return default
    return cur


def pct(n, d):
    try:
        if d and float(d) > 0:
            return round((float(n) / float(d)) * 100, 1)
        return 0
    except:
        return 0


