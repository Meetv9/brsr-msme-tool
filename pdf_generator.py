def generate_brsr_pdf(data, esg_score):
    """
    data: merged dict with Section A keys at top level,
          and nested keys 'section_b', 'p1', 'p2', 'p3', 'p4_5', 'p6', 'p789'
    esg_score: int overall score (0-100)
    Returns: bytes of PDF
    """
    pdf = BRSRReport(orientation="P", unit="mm", format="A4")
    pdf.set_auto_page_break(auto=True, margin=20)
    pdf.add_page()

    # Cover
    render_cover(pdf, data, esg_score)

    # Section A
    pdf.add_page()
    render_section_a(pdf, data)

    # Section B
    if data.get("section_b"):
        render_section_b(pdf, data)

    # Section C — Principles
    render_p1(pdf, data)
    render_p2(pdf, data)
    render_p3(pdf, data)
    render_p45(pdf, data)
    render_p6(pdf, data)
    render_p789(pdf, data)

    # Recommendations
    render_recommendations(pdf, data)

    # Disclaimer
    pdf.ln(6)
    pdf.set_font("Helvetica", "I", 7.5)
    pdf.set_text_color(130, 130, 130)
    pdf.multi_cell(0, 4,
        "Disclaimer: This report has been generated using the BRSR Tool for MSMEs "
        "based on data provided by the company. It is based on the SEBI BRSR format "
        "and simplified for MSME use. This tool does not constitute legal or "
        "regulatory advice. Companies are advised to consult a qualified CA or ESG "
        "consultant for final submission.",
        align="C"
    )

    return bytes(pdf.output())
