    recs = []

    # Section A based
    if data.get("board_female", 0) == 0 and data.get("board_total", 0) > 0:
        recs.append("Add at least one woman to your Board of Directors.")
    if not data.get("has_grievance"):
        recs.append("Set up a formal grievance mechanism "
                    "(dedicated email or register).")

    # Section B based
    b = data.get("section_b", {})
    missing_policies = [code for code in PRINCIPLE_NAMES
                        if b.get(f"{code}_policy") != "Yes"]
    if len(missing_policies) >= 5:
        recs.append(f"{len(missing_policies)} of 9 NGRBC policies not yet in place. "
                    "Use the built-in policy generator to create simple starter policies.")

    # P1
    p1 = data.get("p1", {}) or data.get("c_p1", {})
    if p1 and p1.get("training_conducted") != "Yes":
        recs.append("Conduct basic ethics / anti-bribery training for your team. "
                    "Even a 1-hour session with attendance record counts.")

    # P2
    p2 = data.get("p2", {}) or data.get("c_p2", {})
    if p2 and p2.get("sustainable_sourcing") != "Yes":
        recs.append("Document sustainable sourcing practices - even informal ones. "
                    "Large buyers increasingly check this.")

    # P3
    p3 = data.get("p3", {}) or data.get("c_p3", {})
    if p3 and p3.get("safety_training") != "Yes":
        recs.append("Conduct workplace safety training. "
                    "Even fire-drill + first-aid briefing counts.")

    # P4+5
    p45 = data.get("p4_5", {}) or data.get("c_p45", {})
    if p45 and p45.get("posh_committee") != "Yes":
        recs.append("Form a POSH committee (Prevention of Sexual Harassment). "
                    "Mandatory under Indian law for any workplace with 10+ employees.")

    # P6
    p6 = data.get("p6", {})
    if p6:
        if not str(p6.get("pcb_compliant", "")).startswith("Yes"):
            recs.append("Obtain PCB Consent to Operate (CTO) from your state "
                        "Pollution Control Board - highest priority.")

    # P789
    p789 = data.get("p789", {})
    if p789:
        if p789.get("complaint_record") == "No record":
            recs.append("Start a simple customer complaint register. "
                        "Even a notebook with Date | Name | Issue | Action works.")

    if not recs:
        recs.append("Your BRSR disclosure is comprehensive. Focus on annual "
                    "improvement and year-over-year comparison.")

    for i, rec in enumerate(recs, 1):
        pdf.recommendation(f"{i}. {rec}")
        pdf.ln(0.5)


