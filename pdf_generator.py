def render_section_b(pdf, data):
    """Section B — Management & Process Disclosures (NGRBC)"""
    b = data.get("section_b", {})
    if not b:
        return

    pdf.add_page()
    pdf.section_heading("SECTION B - MANAGEMENT & PROCESS DISCLOSURES")
    pdf.paragraph(
        "This section demonstrates the structures, policies, and processes "
        "put in place toward adopting the 9 NGRBC Principles."
    )

    # ── Policy Management Matrix ──────────────────────────────────────
    pdf.sub_heading("1. Policy & Management Processes (Per Principle)")

    cols = ["Principle", "Policy?", "Approved?", "Translated to Procedures?", "Extends to Suppliers?"]
    widths = [48, 25, 30, 45, 34]
    pdf.table_header(cols, widths)

    for code, name in PRINCIPLE_NAMES.items():
        row = [
            f"{code} - {name[:22]}",
            b.get(f"{code}_policy", "-"),
            b.get(f"{code}_approved", "-"),
            b.get(f"{code}_translated", "-"),
            b.get(f"{code}_value_chain", "-"),
        ]
        shaded = (list(PRINCIPLE_NAMES).index(code) % 2 == 0)
        pdf.table_row(row, widths, shaded=shaded)

    pdf.ln(3)

    # ── Certifications Summary ────────────────────────────────────────
    pdf.sub_heading("2. Certifications & Standards Adopted")
    cert_found = False
    for code, name in PRINCIPLE_NAMES.items():
        certs = b.get(f"{code}_certs", [])
        if certs and certs != ["None"] and len(certs) > 0:
            cert_text = ", ".join([c for c in certs if c != "None"])
            if cert_text:
                pdf.kv_row(f"{code} - {name}", cert_text,
                           shaded=(list(PRINCIPLE_NAMES).index(code) % 2 == 0))
                cert_found = True
    if not cert_found:
        pdf.info_label("No certifications adopted yet.")

    pdf.ln(2)

    # ── Commitments & Goals ───────────────────────────────────────────
    pdf.sub_heading("3. Commitments, Goals & Targets")
    commitment_found = False
    for code, name in PRINCIPLE_NAMES.items():
        commit = b.get(f"{code}_commitment", "")
        if commit and str(commit).strip():
            pdf.set_font("Helvetica", "B", 9)
            pdf.set_text_color(21, 80, 40)
            pdf.cell(0, 5, f"  {code} - {name}", ln=True)
            pdf.set_text_color(0, 0, 0)
            pdf.paragraph(str(commit))
            commitment_found = True
    if not commitment_found:
        pdf.info_label("No specific commitments documented yet.")

    # ── Governance ────────────────────────────────────────────────────
    pdf.add_page()
    pdf.sub_heading("4. Governance, Leadership & Oversight")
    pdf.kv_row("Responsible Person",
               b.get("gov_person_name", "-"), shaded=True)
    pdf.kv_row("Designation", b.get("gov_person_designation", "-"))
    pdf.kv_row("Sustainability Committee",
               b.get("gov_committee", "-"), shaded=True)
    pdf.kv_row("Review Frequency", b.get("gov_review_freq", "-"))
    pdf.kv_row("External Assessment",
               b.get("gov_external_assess", "-"), shaded=True)

    statement = b.get("gov_director_statement", "")
    if statement and str(statement).strip():
        pdf.ln(2)
        pdf.sub_heading("Director's Statement on ESG")
        pdf.paragraph(str(statement))


